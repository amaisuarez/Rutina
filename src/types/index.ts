/** Local calendar date, `YYYY-MM-DD`. Never a UTC timestamp. */
export type ISODate = string
export type ID = string

/** Marks records created by the optional demo mode so they can be removed cleanly. */
interface Demo {
  demo?: boolean
}

/* ------------------------------------------------------------------ */
/* Tasks                                                               */
/* ------------------------------------------------------------------ */

export type Priority = 'low' | 'medium' | 'high' | 'urgent'
export type Difficulty = 'easy' | 'medium' | 'hard' | 'very_hard'
export type TaskStatus = 'pending' | 'in_progress' | 'completed' | 'missed'
export type TaskRecurrenceFreq = 'daily' | 'weekdays' | 'weekly' | 'monthly'

export interface Subtask {
  id: ID
  title: string
  done: boolean
}

export interface Task extends Demo {
  id: ID
  title: string
  description?: string
  date?: ISODate
  startTime?: string
  endTime?: string
  priority: Priority
  difficulty: Difficulty
  estimatedMin?: number
  category: string
  status: TaskStatus
  deadline?: ISODate
  subtasks: Subtask[]
  notes?: string
  /** Set when the task was generated by a recurring series. */
  seriesId?: ID
  completedAt?: string
  createdAt: string
  updatedAt: string
}

export type TaskTemplate = Omit<
  Task,
  'id' | 'date' | 'status' | 'completedAt' | 'createdAt' | 'updatedAt' | 'seriesId' | 'deadline'
>

export interface TaskSeries extends Demo {
  id: ID
  template: TaskTemplate
  freq: TaskRecurrenceFreq
  startDate: ISODate
  until?: ISODate
  /** Instances exist up to and including this date. Prevents re-generation of deleted instances. */
  generatedUntil: ISODate
}

/* ------------------------------------------------------------------ */
/* Fitness                                                             */
/* ------------------------------------------------------------------ */

export type MuscleGroup =
  | 'chest'
  | 'back'
  | 'shoulders'
  | 'arms'
  | 'legs'
  | 'glutes'
  | 'core'
  | 'full_body'
  | 'cardio'
  | 'mobility'

export type ExerciseLevel = 'beginner' | 'intermediate' | 'advanced'

export type Equipment =
  | 'none'
  | 'dumbbells'
  | 'barbell'
  | 'kettlebell'
  | 'bands'
  | 'machine'
  | 'pullup_bar'
  | 'bench'
  | 'mat'
  | 'cardio_machine'

export type Objective = 'strength' | 'hypertrophy' | 'endurance' | 'mobility' | 'fat_loss' | 'recovery'

export interface Exercise {
  id: ID
  name: string
  primary: MuscleGroup
  secondary: MuscleGroup[]
  level: ExerciseLevel
  equipment: Equipment[]
  objectives: Objective[]
  /** `time` exercises log seconds instead of repetitions. */
  kind: 'reps' | 'time'
  sets: number
  reps: string
  restSec: number
  /** Estimated minutes including rests at the recommended volume. */
  minutes: number
  instructions: string[]
  tips: string[]
  custom?: boolean
}

/** Light / standard / challenging / advanced — drives default fitness points. */
export type Intensity = 'light' | 'standard' | 'challenging' | 'advanced'

export interface PlannedExercise {
  exerciseId: ID
  sets: number
  reps: string
  restSec: number
  weight?: number
}

export interface WorkoutTemplate extends Demo {
  id: ID
  name: string
  focus: MuscleGroup[]
  objective: Objective
  intensity: Intensity
  estimatedMin: number
  exercises: PlannedExercise[]
  notes?: string
  createdAt: string
}

export interface ScheduledWorkout extends Demo {
  id: ID
  templateId: ID
  date: ISODate
  time?: string
  status: 'planned' | 'completed' | 'skipped'
  sessionId?: ID
  seriesId?: ID
}

/** A weekly plan: repeat a routine on given weekdays (1 = lunes … 7 = domingo). */
export interface WorkoutSeries extends Demo {
  id: ID
  templateId: ID
  weekdays: number[]
  time?: string
  startDate: ISODate
  until?: ISODate
  generatedUntil: ISODate
}

export interface SetLog {
  reps?: number
  weight?: number
  seconds?: number
  done: boolean
}

export interface SessionExercise {
  exerciseId: ID
  restSec: number
  targetReps: string
  sets: SetLog[]
  skipped?: boolean
  /** Exercise id that this one replaced during the session. */
  replacedFrom?: ID
}

export interface WorkoutSession extends Demo {
  id: ID
  templateId?: ID
  scheduledId?: ID
  name: string
  intensity: Intensity
  date: ISODate
  startedAt: string
  endedAt?: string
  durationMin?: number
  status: 'active' | 'completed' | 'cancelled'
  exercises: SessionExercise[]
  notes?: string
  /** Perceived effort 1–10. */
  effort?: number
}

/* ------------------------------------------------------------------ */
/* Finance (never read by gamification)                                */
/* ------------------------------------------------------------------ */

export type TxType = 'income' | 'expense'

export interface Category {
  id: ID
  name: string
  type: TxType
  color: string
  custom?: boolean
}

export interface Account extends Demo {
  id: ID
  name: string
  kind: 'bank' | 'cash' | 'card' | 'savings' | 'other'
  /** Cents. */
  initialBalance: number
}

export type TxSource = 'manual' | 'imported' | 'recurring'

export interface Transaction extends Demo {
  id: ID
  type: TxType
  /** Always positive, in cents. */
  amount: number
  date: ISODate
  categoryId: ID
  accountId: ID
  description: string
  notes?: string
  recurringId?: ID
  source: TxSource
  createdAt: string
}

export type TxRecurrenceFreq = 'weekly' | 'monthly' | 'yearly'

export interface RecurringRule extends Demo {
  id: ID
  type: TxType
  amount: number
  categoryId: ID
  accountId: ID
  description: string
  freq: TxRecurrenceFreq
  startDate: ISODate
  endDate?: ISODate
  active: boolean
  /** Occurrences up to this date have been generated (or deliberately skipped). */
  generatedThrough?: ISODate
}

export interface Budget {
  /** Cents; null = no overall budget. */
  monthlyTotal: number | null
  byCategory: Record<ID, number>
  demo?: boolean
}

export interface GoalContribution {
  id: ID
  date: ISODate
  amount: number
}

export interface SavingsGoal extends Demo {
  id: ID
  name: string
  target: number
  targetDate?: ISODate
  contributions: GoalContribution[]
  createdAt: string
}

/* ------------------------------------------------------------------ */
/* Gamification                                                        */
/* ------------------------------------------------------------------ */

export type PointCategory = 'fitness' | 'productivity'

export interface PointEntry extends Demo {
  id: ID
  category: PointCategory
  sourceType: 'task' | 'workout'
  sourceId: ID
  /** Positive for awards, negative for reversals. */
  points: number
  kind: 'award' | 'reversal' | 'recalculation'
  /** Date the activity was completed; decides which month the points count for. */
  date: ISODate
  reason: string
  createdAt: string
}

export interface ScoringConfig {
  task: Record<Difficulty, number>
  /** Bonus for long tasks: `perHour` points per full hour beyond the first, capped at `max`. */
  taskDuration: { enabled: boolean; perHour: number; max: number }
  workout: Record<Intensity, number>
  /** Bonus per 15 min beyond `baselineMin`, capped at `max`. */
  workoutDuration: { baselineMin: number; per15: number; max: number }
  /** Below this share of completed sets, base points scale down proportionally. */
  minCompletion: number
  /** Hard cap for a single workout session. */
  sessionCap: number
}

export interface UnlockedAchievement {
  id: string
  unlockedAt: string
}

/* ------------------------------------------------------------------ */
/* Settings                                                            */
/* ------------------------------------------------------------------ */

export type WidgetId =
  | 'focus'
  | 'workout'
  | 'money'
  | 'weekTasks'
  | 'weekFitness'
  | 'budget'
  | 'points'
  | 'streak'
  | 'goals'
  | 'upcoming'

export interface Settings {
  name: string
  currency: string
  goals: {
    dailyTasks: number
    weeklyTasks: number
    weeklyWorkouts: number
    monthlyPoints: number
  }
  scoring: ScoringConfig
  equipment: Equipment[]
  taskCategories: string[]
  dashboard: { order: WidgetId[]; hidden: WidgetId[] }
  onboarded: boolean
  hideAmounts: boolean
}
