/** Formats target reps for display; `time` exercises store seconds. */
export function formatTarget(ex: Pick<Exercise, 'kind'>, reps: string): string {
  if (ex.kind !== 'time') return `${reps} reps`
  const s = parseInt(reps, 10)
  if (!s) return reps
  return s >= 120 ? `${Math.round(s / 60)} min` : `${s} s`
}
