/** Estimated minutes for an exercise at its recommended volume (work + rest). */
function estimate(sets: number, reps: string, restSec: number, kind: 'reps' | 'time'): number {
  const work = kind === 'time' ? parseInt(reps, 10) || 30 : 40
  return Math.max(2, Math.round((sets * (work + restSec)) / 60))
}

